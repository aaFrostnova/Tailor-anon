"""Export distinct-input live results and separate completed holdout diagnostics.

Reads frozen experiment outputs; never changes inputs, decisions, or measurements.
"""
import collections
import argparse
import datetime
import csv
import hashlib
import json
import shutil
import statistics
from pathlib import Path

OUT = Path(__file__).resolve().parent
PAPER = Path('/data/tailor/paper')
RUN = Path('/data/tailor/home/outputs/rigor_editing_only_20260911/unified_ba_20260914')
ATLAS = Path('/data/tailor/home/outputs/request_atlas_6532_20260917')
CLASSES = ['C1', 'C2', 'C3', 'C4', 'C5']
METHODS = {'VINE': 'single_baselines/S_VINE', 'TrustMark': 'single_baselines/S_TrustMark',
           'VideoSeal': 'single_baselines/S_VideoSeal'}
LABELS = {'VINE': 'VINE only', 'TrustMark': 'TrustMark only', 'VideoSeal': 'VideoSeal only'}
HASHES = {}


def read(path):
    raw = Path(path).read_bytes()
    HASHES[str(path)] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)


def write_json(path, value, compact=False):
    Path(path).write_text(json.dumps(value, indent=None if compact else 2, allow_nan=False) + '\n')


def signed(d, field):
    raw = json.dumps({k: v for k, v in d.items() if k != field}, sort_keys=True,
                     separators=(',', ':'), allow_nan=False).encode()
    assert hashlib.sha256(raw).hexdigest() == d[field], field


def key(d):
    return tuple(sorted(d['attacks'])), d['fpr'], d.get('min_psnr', d.get('min_psnr_db')), d['max_ms']


def table(path, caption, label, headings, rows, spec, note='', small='small', standalone=True):
    # A block with standalone off is a piece of a larger table, so it opens no float
    # and carries no caption of its own; the table that includes it supplies both.
    tex = [r'% Generated by export_paper_data.py from audited distinct-input records.']
    tex += ([r'\begin{table}[!htbp]'] if standalone else [])
    tex += [r'\centering', '\\' + small]
    tex += ([r'\caption{' + caption + '}', r'\label{' + label + '}'] if standalone else [])
    tex += [r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{@{}' + spec + r'@{}}',
           r'\toprule', ' & '.join(headings) + r' \\', r'\midrule']
    tex += [' & '.join(row) + r' \\' for row in rows]
    tex += [r'\bottomrule', r'\end{tabular}']
    if note:
        tex += [r'\par\smallskip', r'\begin{minipage}{\linewidth}\footnotesize', note, r'\end{minipage}']
    if standalone:
        tex += [r'\end{table}']
    (PAPER / 'tab' / path).write_text('\n'.join(tex) + '\n')


def pct(v, provisional=False):
    return (r'$\ge ' + f'{v:.2f}' + r'$' if provisional and v < 100 else f'{v:.2f}')


def main():
    summary = read(OUT / 'summary.json')
    assert summary['validation']['passed']
    manifest = read(OUT / 'deduplicated_requests.json')
    specs = manifest['rows']
    assert len(specs) == 6532 and sum(s['multiplicity'] for s in specs) == 10000
    by_id = {(s['cls'], i): s for s in specs for i in s['original_indices']}
    evidence = read(RUN / 'source_hashes.json')
    for cls in CLASSES:
        p = RUN / 'fixed/inputs' / (cls + '.json')
        read(p)
        assert HASHES[str(p)] == evidence[str(p)]

    live = {}
    for name, folder in METHODS.items():
        p = RUN / folder
        decisions = read(p / 'selection/decisions.json')
        selection = read(p / 'plans/final_selection.json')
        signed(selection, 'selection_sha256')
        assert decisions['complete'] and decisions['no_final_feedback']
        assert decisions['total'] == 20000
        indexed = {tuple([r['key'].split('/')[0], r['key'].split('/')[1], int(r['key'].split('/')[2])]): r
                   for r in decisions['rows']}
        frozen = {(r['class'], r['arm'], r['request_id']): r for r in selection['requests']}
        assert len(indexed) == len(frozen) == 20000
        for ident, r in indexed.items():
            f = frozen[ident]
            assert key(f['inputs']) == key(by_id[(ident[0], ident[2])]['inputs'])
            assert r['passed'] == (f['selected'] is not None)
            assert f['source']['sha256'] == HASHES[str(p / 'selection/decisions.json')]
            assert r['metrics']['acceptance_protocol'] == 'unified_raw_ba_v1'
            assert r['passed'] == r['metrics']['passed']
            if f['selected']:
                assert f['selected']['selection_metrics'] == r['metrics']
            if ident[1] == '04':
                other = indexed[(ident[0], '06', ident[2])]
                assert {k:v for k,v in r.items() if k != 'key'} == {k:v for k,v in other.items() if k != 'key'}
        # Validate the source selection tasks with the original result validator.
        import sys
        sys.path.insert(0, str(RUN / 'code'))
        from final_measurement import validate_result
        tasks = read(p / 'plans/selection_tasks.json')
        signed(tasks, 'plan_sha256')
        assert tasks['plan_sha256'] == decisions['plan_sha256']
        for task in tasks['tasks']:
            result = read(p / 'selection/cache' / task['task_id'] / 'result.json')
            validate_result(task, result)
        all04 = [r for ident, r in indexed.items() if ident[1] == '04']
        assert sum(r['passed'] for r in all04) * 2 == decisions['selected']
        assert sum(not r['metrics']['latency_pass'] for r in all04) == 0
        rows = []
        for s in specs:
            r = indexed[(s['cls'], '04', s['representative_i'])]
            comparisons = [{k:v for k,v in indexed[(s['cls'], '04', i)].items() if k != 'key'}
                           for i in s['original_indices']]
            assert all(v == comparisons[0] for v in comparisons)
            rows.append((s, r))
        stats = []
        for scope in ['Overall'] + CLASSES:
            part = [(s, r) for s,r in rows if scope == 'Overall' or s['cls'] == scope]
            n = sum(r['passed'] for s,r in part)
            stats.append(dict(scene=scope, n=len(part), accepted=n, percent=100*n/len(part)))
        good = [r['metrics'] for s,r in rows if r['passed']]
        live[name] = dict(complete=True, metrics=stats, original_accepted=sum(r['passed'] for r in all04),
            macro_percent=statistics.mean(r['percent'] for r in stats[1:]),
            duplicate_outcomes_equal=True, paired_arms_equal=True, selection_tasks_validated=len(tasks['tasks']),
            own_success_means=dict(n=len(good), psnr_db=statistics.mean(r['embedding_psnr_db']['mean'] for r in good),
                capacity_bits=statistics.mean(r['capacity_bits_estimate'] for r in good),
                measured_latency_ms=statistics.mean(r['latency_max_attack_mean_ms'] for r in good)))

    # Keep the original execution sample. Fix one outcome-independent representative
    # within its union and use it in both overlapping reporting cohorts.
    subset = read(RUN / 'shared_table_20260916/ablation_1000_v1/requests.json')
    grouped = collections.defaultdict(list)
    for r in subset['rows']:
        s = by_id[(r['cls'], r['i'])]
        assert key(r['request']) == key(s['inputs'])
        grouped[s['spec_id']].append(r)
    ablation_rows = []
    for sid, members in grouped.items():
        r = min(members, key=lambda r: (r['cls'], r['i']))
        ablation_rows.append(dict(spec_id=sid, cls=r['cls'], representative_i=r['i'],
            original_indices=sorted(m['i'] for m in members), cohorts=sorted({m['cohort'] for m in members}),
            edge_tags=r['edge_tags']))
    cohort_counts = {c:sum(c in r['cohorts'] for r in ablation_rows) for c in ['representative','targeted']}
    assert len(ablation_rows)==924 and cohort_counts==dict(representative=388,targeted=553)
    overlap=sum(len(r['cohorts'])==2 for r in ablation_rows)
    assert overlap==17
    ablation = dict(original_ids=1000, unique_specs=924, cohort_counts=cohort_counts, overlap=overlap,
        representative_rule='Smallest original index within the frozen ablation union; common across cohorts, methods, arms',
        outcome_data_used=False, execution_subset_changed=False,
        by_class=dict(collections.Counter(r['cls'] for r in ablation_rows)),
        tags_nonexclusive=dict(collections.Counter(t for r in ablation_rows for t in r['edge_tags'])), rows=ablation_rows)

    report = dict(schema='deduplicated_live_main_20260917', primary_metric='live request satisfaction',
        original_records=10000, unique_specifications=6532, request_distribution=summary['distribution'],
        fixed_control_live=live, main_live_snapshot=summary['main_live'],
        shared_greedy_live_complete=False, main_live_complete=False,
        supplemental_independent_final={m:summary['results'][m] for m in METHODS},
        ablation_reporting={k:v for k,v in ablation.items() if k!='rows'}, source_sha256=HASHES,
        endpoint_change='User requested live acceptance as the primary endpoint after inspecting partial results; independent final remains supplementary.')
    write_json(PAPER / 'data/evaluation_deduplicated_20260917.json', report)
    write_json(PAPER / 'data/request_specifications_6532.json', manifest, compact=True)
    write_json(PAPER / 'data/ablation_unique_reporting.json', ablation)
    write_json(OUT / 'live_reporting_validation.json', dict(passed=True, baseline_count=len(METHODS),
        baseline_selection_tasks=sum(x['selection_tasks_validated'] for x in live.values()),
        duplicate_live_outcomes_equal=True, frozen_execution_changed=False, main_rows_provisional=True,
        primary_endpoint_change_disclosed=True))

    overview = summary['distribution']['classes'][1:]
    names = ['Signal / re-encoding','Geometry','Regeneration / editing','Watermark removal','Broad attack coverage']
    table('request_overview.tex', r'\textbf{Distinct request specifications.} Each row counts unique four-input tuples after deduplication. Attack sets count distinct unordered memberships, without FPR or quality/latency budgets.',
          'tab:request-set', ['Class','Scenario','Specifications',r'Share (\%)','Attack sets'],
          [[r['scene'],n,f"{r['deduplicated_n']:,}",f"{r['share_percent']:.2f}",str(r['attack_sets'])] for r,n in zip(overview,names)] +
          [['Total','', '6,532','100.00','192']], 'llrrr', standalone=False)

    main_rows=[]
    for m in METHODS:
        d=live[m];rates=[d['metrics'][0]['percent'],d['macro_percent']]+[x['percent'] for x in d['metrics'][1:]]
        main_rows.append([LABELS[m],'-']+[pct(x) for x in rates])
    for arm in ['04','06']:
        main_rows.append(['Greedy', '0.'+arm]+[r'\FILL']*7)
    for arm in ['04','06']:
        d=summary['main_live']['arms'][arm]
        rates=[d['metrics'][0]['deduplicated_live_percent'],d['class_equal_macro_live_percent']]+[x['deduplicated_live_percent'] for x in d['metrics'][1:]]
        main_rows.append([r'\rowcolor{hl} \sys{}','0.'+arm]+[pct(x,True) for x in rates])
    table('eval_current_main.tex', r'\textbf{Live-validated request satisfaction (\%).} Overall counts each of 6,532 specifications once; Macro averages the five class rates equally. C1--C5 denominators are 1,551/1,532/873/1,033/1,543. Fixed controls have complete live evidence. The full-method rows are provisional lower bounds from the September 17 live snapshot: unfinished requests remain in the denominator. Greedy uses the shared model; its live evaluation is still incomplete. Neither live acceptance nor these bounds claim independent-image generalization.',
        'tab:main', ['Method','$m_0$','Overall','Macro','C1','C2','C3','C4','C5'],main_rows,'llrrrrrrr')

    status_rows=[]
    for arm in ['04','06']:
        d=summary['main_live']['arms'][arm]['metrics'][0]
        status_rows.append(['0.'+arm]+[f"{d[k]:,}" for k in ['accepted','pending','initial_model_unsat','live_exhausted']])
    start=datetime.datetime.fromisoformat(summary['main_live']['snapshot_started_at'])
    end=datetime.datetime.fromisoformat(summary['main_live']['snapshot_finished_at'])
    interval=f'{start:%Y-%m-%d %H:%M:%S} to {end:%Y-%m-%d %H:%M:%S} UTC'
    table('eval_live_progress.tex',r'\textbf{Full-method live snapshot on 6,532 specifications per arm.} Initial model infeasibility remains eligible for the registered fallback. Missing measurements and current candidate exhaustion are distinct from global library infeasibility. Counts are read sequentially from '+interval+'; these are not terminal campaign totals.',
        'tab:live-progress',['$m_0$','Live accepted','Awaiting evidence','Initial model UNSAT','Candidates exhausted'],status_rows,'lrrrr')

    rows=[]
    for m in METHODS:
        q=live[m]['own_success_means']
        rows.append([LABELS[m],f"{q['n']:,}",f"{q['psnr_db']:.2f}",f"{q['capacity_bits']:.2f}",f"{q['measured_latency_ms']:.2f}"])
    table('eval_current_quality.tex',r'\textbf{Descriptive measurements on the live-accepted specifications of each fixed control.} Each specification has equal weight within the accepted set of that method. PSNR and capacity use selection-role measurements; latency is the measured maximum of attack-wise mean deployment times for these controls. The successful sets differ, so these are not paired advantages. Full-method and shared-model Greedy quality summaries await completed live selection; their selection latency model must not be relabelled as measured timing.',
        'tab:main-quality',['Method','$n$','PSNR (dB)','Capacity (bits)','Measured latency (ms)'],rows,'lrrrr')

    rows=[]
    for m in METHODS:
        f=summary['results'][m]['metrics'][0];l=live[m]
        rows.append([LABELS[m],f"{100*l['original_accepted']/10000:.2f}",f"{l['metrics'][0]['percent']:.2f}",f"{l['macro_percent']:.2f}",f"{f['deduplicated_pass']:,}",f"{f['deduplicated_percent']:.2f}"])
    table('dedup_sensitivity.tex',r'\textbf{Reporting weights and supplementary held-out results for completed controls.} Original live weights the 10,000 sampled records; distinct live weights the 6,532 specifications equally; Macro live averages class rates. Held-out counts use all 6,532 specifications and additionally require recovery, PSNR, and measured latency on the separate image role. These supplementary outcomes do not change whether a configuration was live accepted.',
        'tab:dedup-sensitivity',['Method',r'Original live (\%)',r'Distinct live (\%)',r'Macro live (\%)','Held-out $n$',r'Held-out (\%)'],rows,'lrrrrr')

    old=(PAPER/'tab/request_distribution.tex').read_text()
    old=old.replace('The frozen benchmark has 2{,}000 requests per class (10{,}000 total), each evaluated at\ninitial rate margins 0.04 and 0.06. The tables give realized budget choices and FPR counts, before\nselection.', 'The benchmark contains 6{,}532 distinct four-input specifications from 10{,}000 sampled records. Each specification is evaluated at initial rate margins 0.04 and 0.06. The tables give realized budget choices and deduplicated FPR counts.')
    start=old.index('C1 &',old.index('\\textbf{Class / FPR}'));end=old.index('\\bottomrule',start)
    fprs=[.1,.01,1e-4,1e-6,1e-9,2**-37]
    rows=[]
    for scope in CLASSES+['Overall']:
        n=[next(r['deduplicated_n'] for r in summary['distribution']['budgets'] if r['scene']==scope and r['dimension']=='fpr' and r['value']==v) for v in fprs]
        rows.append(('\\textbf{Total}' if scope=='Overall' else scope)+' & '+' & '.join(f'{v:,}' for v in n)+r' \\')
    old=old[:start]+'\n'.join(rows)+'\n'+old[end:]
    old=old.replace('100 requests (5\\%)','100 distinct requests (11.45\\% of C3; 1.53\\% overall)')
    old=old.replace('877 requests at 0.3,\n919 at 0.5, and 204 at 0.7; 505 requests', '570 distinct requests at 0.3,\n278 at 0.5, and 185 at 0.7; 319 distinct requests')
    (PAPER/'tab/request_distribution.tex').write_text(old)

    shutil.copy2(ATLAS/'06_multidimensional_map.pdf', PAPER/'figures/request_map_6532.pdf')
    write_json(PAPER/'data/request_map_analysis.json',read(ATLAS/'analysis.json'))
    print('LIVE',json.dumps(live,indent=2))
    print('ABLATION',json.dumps({k:v for k,v in ablation.items() if k!='rows'},indent=2))


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--analysis-root',type=Path,default=OUT)
    parser.add_argument('--paper-root',type=Path,default=PAPER)
    parser.add_argument('--campaign-root',type=Path,default=RUN)
    parser.add_argument('--atlas-root',type=Path,default=ATLAS)
    args=parser.parse_args()
    OUT,PAPER,RUN,ATLAS=args.analysis_root,args.paper_root,args.campaign_root,args.atlas_root
    main()
